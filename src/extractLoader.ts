// region imports
import type {LoaderContext} from 'webpack'

import {escapeRegularExpressions} from 'clientnode'
import {relative} from 'path'
// endregion
// region types
export interface LoaderConfiguration {
    /*
        Directory (relative to the output path) the extracted content will be
        located in. Used to resolve asset references when the public path is
        determined automatically.
    */
    outputDirectory?: string
    /*
        Public path to use for asset references while executing the module.
        Defaults to the configured output public path.
    */
    publicPath?: string
}
// endregion
// region constants
/*
    NOTE: Executed modules may need to resolve urls (e.g. "new URL(request,
    import.meta.url)" generated by the "html-loader"), so we have to provide
    absolute urls while executing and remove these markers afterward.
*/
export const BASE_URI = 'webpack://'
export const ABSOLUTE_PUBLIC_PATH = `${BASE_URI}/weboptimizer-extract-loader/`
export const AUTO_PUBLIC_PATH =
    `${BASE_URI}/weboptimizer-extract-loader-auto/`
export const SINGLE_DOT_PATH_SEGMENT =
    '__weboptimizer_extract_loader_single_dot_path_segment__'
// endregion
/**
 * Determines the extracted content from given module exports.
 * @param exports - Module exports to extract content from.
 * @returns Extracted string content.
 */
export const determineContent = (exports: unknown): string => {
    if (
        exports !== null &&
        typeof exports === 'object' &&
        'default' in exports
    )
        exports = exports.default

    if (typeof exports === 'string')
        return exports

    throw new Error(
        'Module to extract does not export a string but a value of type ' +
        `"${typeof exports}".`
    )
}
/**
 * Determines the absolute public path to use while executing the module.
 * @param publicPath - Configured public path.
 * @returns Absolute public path.
 */
export const determineExecutionPublicPath = (publicPath: unknown): string => {
    if (typeof publicPath !== 'string' || publicPath === 'auto')
        return AUTO_PUBLIC_PATH

    if (/^[a-zA-Z][a-zA-Z\d+\-.]*?:/.test(publicPath))
        return publicPath

    return ABSOLUTE_PUBLIC_PATH +
        publicPath.replace(/\./g, SINGLE_DOT_PATH_SEGMENT)
}
/**
 * Removes all markers introduced to execute the module.
 * @param content - Content to clean up.
 * @param outputDirectory - Directory the content will be located in.
 * @returns Cleaned up content.
 */
export const removeMarkers = (
    content: string, outputDirectory = '.'
): string => {
    let undoPath = relative(outputDirectory, '.').replace(/\\/g, '/')
    if (undoPath)
        undoPath += '/'

    return content
        .replace(
            new RegExp(escapeRegularExpressions(AUTO_PUBLIC_PATH), 'g'),
            undoPath
        )
        .replace(
            new RegExp(escapeRegularExpressions(ABSOLUTE_PUBLIC_PATH), 'g'),
            ''
        )
        .replace(new RegExp(SINGLE_DOT_PATH_SEGMENT, 'g'), '.')
}
/**
 * Executes the module described by all remaining loaders at build time and
 * replaces it with its (string) export. This allows turning the output of
 * the "html-loader" (a javascript module) into plain html again.
 * NOTE: This replaces the deprecated "extract-loader" package by using
 * webpack's native "importModule" api.
 * @param remainingRequest - Request of all following loaders and resource.
 * @returns Extracted content.
 */
export const pitch = async function(
    this: LoaderContext<LoaderConfiguration>, remainingRequest: string
): Promise<string> {
    const options: LoaderConfiguration = this.getOptions()

    const exports: unknown = await this.importModule(
        /*
            NOTE: Force a javascript module type to avoid applying the asset
            module type of the outer rule to the executed module. "!!" avoids
            applying all configured loaders twice.
        */
        `${this.resourcePath}.webpack[javascript/auto]!=!!!` +
        remainingRequest,
        {
            baseUri: `${BASE_URI}/`,
            publicPath: determineExecutionPublicPath(
                typeof options.publicPath === 'string' ?
                    options.publicPath :
                    this._compilation?.outputOptions.publicPath
            )
        }
    )

    return removeMarkers(determineContent(exports), options.outputDirectory)
}
/**
 * Never called since the pitching phase always returns a result.
 * @param source - Given source.
 * @returns Given source.
 */
export const loader = (source: string): string => source

export default loader
